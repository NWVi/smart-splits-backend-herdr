local h = require('tests.helpers')

local no_neighbor = { focus = { changed = false, reason = 'no_neighbor' } }
local split_ok = { pane = { pane_id = 'ws1:p3' } }
local swap_ok = { swap = { changed = true } }

describe('move()', function()
  before_each(function()
    h.reset_backend()
    h.enter_session()
  end)

  after_each(function()
    h.reset_backend()
  end)

  it('focuses the neighboring herdr pane', function()
    local backend = require('smart-splits-backend-herdr')
    local calls = h.stub_system({ focus = { focus = { changed = true } } })
    assert.is_true(backend.move('left'))
    assert.same({ { 'herdr', 'pane', 'focus', '--direction', 'left', '--current' } }, calls)
  end)

  it('returns false at edge with at_edge=stop', function()
    local backend = require('smart-splits-backend-herdr')
    local calls = h.stub_system({ focus = no_neighbor })
    assert.is_false(backend.move('right', { at_edge = 'stop' }))
    assert.are.equal(1, #calls)
  end)

  it('returns false at edge with at_edge=wrap', function()
    local backend = require('smart-splits-backend-herdr')
    local calls = h.stub_system({ focus = no_neighbor })
    assert.is_false(backend.move('right', { at_edge = 'wrap' }))
    assert.are.equal(1, #calls)
  end)

  it('splits right at edge with at_edge=split', function()
    local backend = require('smart-splits-backend-herdr')
    local calls = h.stub_system({ focus = no_neighbor, split = split_ok })
    assert.is_true(backend.move('right', { at_edge = 'split' }))
    assert.are.equal(2, #calls)
    assert.same({ 'herdr', 'pane', 'split', '--direction', 'right', '--current', '--focus' }, calls[2])
  end)

  it('splits right and swaps when splitting left', function()
    local backend = require('smart-splits-backend-herdr')
    local calls = h.stub_system({ focus = no_neighbor, split = split_ok, swap = swap_ok })
    assert.is_true(backend.move('left', { at_edge = 'split' }))
    assert.same({ 'herdr', 'pane', 'split', '--direction', 'right', '--current', '--focus' }, calls[2])
    assert.same({ 'herdr', 'pane', 'swap', '--direction', 'right', '--current' }, calls[3])
  end)

  it('splits down and swaps when splitting up', function()
    local backend = require('smart-splits-backend-herdr')
    local calls = h.stub_system({ focus = no_neighbor, split = split_ok, swap = swap_ok })
    assert.is_true(backend.move('up', { at_edge = 'split' }))
    assert.same({ 'herdr', 'pane', 'split', '--direction', 'down', '--current', '--focus' }, calls[2])
    assert.same({ 'herdr', 'pane', 'swap', '--direction', 'down', '--current' }, calls[3])
  end)

  it('returns false when the split fails', function()
    local backend = require('smart-splits-backend-herdr')
    local calls = h.stub_system({ focus = no_neighbor, split = false })
    assert.is_false(backend.move('left', { at_edge = 'split' }))
    assert.are.equal(2, #calls)
  end)

  it('does not split when the focus command fails', function()
    local backend = require('smart-splits-backend-herdr')
    local calls = h.stub_system({ focus = false })
    assert.is_false(backend.move('right', { at_edge = 'split' }))
    assert.are.equal(1, #calls)
  end)

  it('returns false on malformed output', function()
    local backend = require('smart-splits-backend-herdr')
    h.stub_system({ focus = 'not json' })
    assert.is_false(backend.move('right'))
  end)

  it('returns false without running herdr outside herdr', function()
    local backend = require('smart-splits-backend-herdr')
    vim.env.HERDR_ENV = nil
    local calls = h.stub_system({ focus = { focus = { changed = true } } })
    assert.is_false(backend.move('right'))
    assert.are.equal(0, #calls)
  end)

  it('returns false without running herdr when disabled by config', function()
    local backend = require('smart-splits-backend-herdr')
    backend.setup({ enable = false })
    local calls = h.stub_system({ focus = { focus = { changed = true } } })
    assert.is_false(backend.move('right'))
    assert.are.equal(0, #calls)
  end)
end)
