local h = require('tests.helpers')

describe('detect()', function()
  before_each(function()
    h.reset_backend()
  end)

  after_each(function()
    h.reset_backend()
  end)

  it('returns true inside herdr with herdr executable', function()
    local backend = require('smart-splits-backend-herdr')
    h.enter_session()
    h.stub_executable(true)
    assert.is_true(backend.detect())
  end)

  it('returns false outside herdr', function()
    local backend = require('smart-splits-backend-herdr')
    h.stub_executable(true)
    assert.is_false(backend.detect())
  end)

  it('returns false when herdr is not executable', function()
    local backend = require('smart-splits-backend-herdr')
    h.enter_session()
    h.stub_executable(false)
    assert.is_false(backend.detect())
  end)

  it('returns false when disabled by config', function()
    local backend = require('smart-splits-backend-herdr')
    h.enter_session()
    h.stub_executable(true)
    backend.setup({ enable = false })
    assert.is_false(backend.detect())
  end)

  it('does not run herdr', function()
    local backend = require('smart-splits-backend-herdr')
    local calls = h.stub_system({})
    h.enter_session()
    h.stub_executable(true)
    backend.detect()
    assert.are.equal(0, #calls)
  end)
end)
