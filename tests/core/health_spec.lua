local h = require('tests.helpers')

describe('health()', function()
  before_each(function()
    h.reset_backend()
  end)

  after_each(function()
    h.reset_backend()
  end)

  it('does not error inside herdr', function()
    local backend = require('smart-splits-backend-herdr')
    h.enter_session()
    h.stub_executable(true)
    assert.has_no.errors(function()
      backend.health()
    end)
  end)

  it('does not error outside herdr without herdr executable', function()
    local backend = require('smart-splits-backend-herdr')
    h.stub_executable(false)
    assert.has_no.errors(function()
      backend.health()
    end)
  end)
end)
